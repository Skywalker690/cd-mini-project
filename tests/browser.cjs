/* Optional browser regression suite. Requires Playwright for development only. */
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
const {pathToFileURL} = require('node:url');
(async()=>{
  const browser=await chromium.launch({headless:true,channel:'chrome'});
  const page=await browser.newPage({viewport:{width:1440,height:1050},deviceScaleFactor:1});
  await fs.mkdir('.build',{recursive:true});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.goto(pathToFileURL(path.resolve('index.html')).href);
  await page.getByText('Compilation successful',{exact:true}).waitFor();
  await page.screenshot({path:'.build/qa-browser-desktop.png',fullPage:true});
  assert.match(await page.locator('#output-text').innerText(),/Hello, World!/);
  await page.getByRole('tab',{name:/Tokens/}).click();
  assert.equal(await page.locator('#tokens-container tbody tr').count(),27);
  await page.getByRole('tab',{name:/AST/}).click();
  assert.match(await page.locator('#ast-container').innerText(),/Declaration/);
  await page.locator('#collapse-tree').click();
  assert.equal(await page.locator('#ast-container details[open]').count(),0);
  await page.locator('#expand-tree').click();
  assert.ok(await page.locator('#ast-container details[open]').count()>0);
  await page.getByRole('tab',{name:/Symbols/}).click();
  assert.equal(await page.locator('#symbols-container tbody tr').count(),2);
  for(const [example,phase]of [['lexical','Lexical'],['syntax','Syntax'],['semantic','Semantic']]){
    await page.locator('#example-select').selectOption(example);
    assert.match(await page.locator('#diagnostics').innerText(),new RegExp(phase+' error','i'));
    assert.equal(await page.locator('#output-region').isVisible(),false);
  }
  assert.equal(await page.locator('.diagnostic').count(),3);
  await page.locator('#example-select').selectOption('hello');
  await page.locator('#source').fill('print("Changed");');
  assert.equal(await page.locator('#export-report').isDisabled(),true);
  assert.equal(await page.locator('#output-region').isVisible(),false);
  await page.locator('#source').press('Control+Enter');
  assert.equal(await page.locator('#output-text').innerText(),'Changed');
  const [report] = await Promise.all([page.waitForEvent('download'),page.locator('#export-report').click()]);
  const reportPath=await report.path(); const json=JSON.parse(await fs.readFile(reportPath,'utf8'));
  assert.equal(json.source,'print("Changed");'); assert.deepEqual(json.output,['Changed']);
  const [source] = await Promise.all([page.waitForEvent('download'),page.locator('#save-source').click()]);
  assert.equal(await fs.readFile(await source.path(),'utf8'),'print("Changed");');
  await page.getByRole('tab',{name:/AST/}).click();
  const [ast] = await Promise.all([page.waitForEvent('download'),page.locator('#save-ast').click()]);
  assert.equal(JSON.parse(await fs.readFile(await ast.path(),'utf8')).type,'Program');
  await page.locator('#source-file').setInputFiles({name:'upload.str',mimeType:'text/plain',buffer:Buffer.from('print("Imported");')});
  await page.getByText('Source file opened.',{exact:true}).waitFor();
  assert.equal(await page.locator('#source-filename').innerText(),'upload.str');
  assert.equal(await page.locator('#output-text').innerText(),'Imported');
  await page.locator('#source-file').setInputFiles({name:'oversize.str',mimeType:'text/plain',buffer:Buffer.from('\n'.repeat(200000))});
  await page.waitForTimeout(200);
  assert.ok((await page.locator('#source').inputValue())==='print("Imported");','Oversized imports must preserve the previous source');
  assert.equal(await page.locator('#source-filename').innerText(),'upload.str');
  assert.match(await page.locator('#toast').innerText(),/source.*limit/i);
  await page.locator('#source').fill('print("<img src=x onerror=alert(1)>");');
  await page.locator('#compile-button').click();
  assert.equal(await page.locator('#output-text img').count(),0);
  assert.match(await page.locator('#output-text').innerText(),/<img/);
  await page.locator('nav [data-dialog="guide-dialog"]').click();
  assert.equal(await page.locator('#guide-dialog').isVisible(),true);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#guide-dialog').isVisible(),false);
  await page.locator('nav [data-dialog="project-dialog"]').click();
  assert.equal(await page.locator('#project-dialog').isVisible(),true);
  await page.locator('#project-dialog [data-close]').click();
  await page.locator('#example-select').selectOption('hello');
  await page.locator('#tab-output').focus(); await page.keyboard.press('ArrowRight');
  assert.equal(await page.locator('#tab-tokens').getAttribute('aria-selected'),'true');
  await page.locator('#tab-output').click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'.build/qa-browser-mobile.png',fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  await page.locator('#example-select').selectOption('semantic');
  assert.equal(await page.locator('.diagnostic').count(),3);
  await page.goto(pathToFileURL(path.resolve('index.html')).href);
  await page.getByText('Compilation successful',{exact:true}).waitFor();
  assert.match(await page.locator('#output-text').innerText(),/Hello, World!/);
  assert.deepEqual(errors,[]);
  console.log('Browser checks passed: results, examples, AST controls, keyboard, import/export, stale state, safe rendering, dialogs, mobile layout and direct file:// use.');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
